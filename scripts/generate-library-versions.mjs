#!/usr/bin/env node
/**
 * generate-library-versions — projects each library's published version and its
 * latest changelog date into a typed constant, so the JSON-LD layer can emit
 * real `softwareVersion` / `dateModified` values without hand-maintained maps.
 *
 * Reads every `projects/<dir>/package.json` whose name starts with `ng-hub-ui`
 * plus the head entry of its `CHANGELOG.md` (`## [x.y.z] - YYYY-MM-DD`).
 * Runs on `prestart` / `prebuild` / `pretest`, mirroring generate-version.mjs.
 *
 * Output: src/app/seo/library-versions.generated.ts
 * Run:    npm run generate:library-versions
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PROJECTS = path.join(ROOT, 'projects');

const versions = {};
const lastModified = {};

for (const dir of fs.readdirSync(PROJECTS).sort()) {
	const pkgPath = path.join(PROJECTS, dir, 'package.json');
	if (!fs.existsSync(pkgPath)) continue;
	const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf8'));
	if (!String(pkg.name ?? '').startsWith('ng-hub-ui')) continue;
	versions[dir] = pkg.version;

	const changelogPath = path.join(PROJECTS, dir, 'CHANGELOG.md');
	if (fs.existsSync(changelogPath)) {
		const head = fs.readFileSync(changelogPath, 'utf8').match(/^## \[[^\]]+\] - (\d{4}-\d{2}-\d{2})/m);
		if (head) {
			lastModified[dir] = head[1];
		}
	}
}

const render = (obj) =>
	Object.entries(obj)
		.map(([k, v]) => `\t'${k}': '${v}'`)
		.join(',\n');

const output = `// Generated by scripts/generate-library-versions.mjs — do not edit by hand.

/** Published version of each library, keyed by its projects/ directory (== SEO route). */
export const LIBRARY_VERSIONS: Record<string, string> = {
${render(versions)}
};

/** Date of each library's latest changelog entry (ISO date). */
export const LIBRARY_LAST_MODIFIED: Record<string, string> = {
${render(lastModified)}
};
`;

fs.writeFileSync(path.join(ROOT, 'src/app/seo/library-versions.generated.ts'), output);
console.log(`[library-versions] ${Object.keys(versions).length} libraries projected`);
